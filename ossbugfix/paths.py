"""paths.py — where everything lives.

Two trees, deliberately separate:

  domains/<domain>/   committed. The registry, the curated findings, the docs.
  work/<domain>/      ignored by git. Mirrors and intermediate frames, all of
                      which are reproducible from the registry, so losing the
                      tree costs time but never data.

`OSS_BUGFIXES_ROOT` overrides the repository root (tests use it); `OSS_BUGFIXES_WORK`
overrides the work tree, which matters when the mirrors must land on a different
disk from the checkout.
"""
from __future__ import annotations

import os
from pathlib import Path

__all__ = [
    "repo_root", "work_root", "domains_root", "domain_dir", "registry_path",
    "domain_data_dir", "domain_docs_dir", "work_dir", "mirror_dir",
    "commits_dir", "candidates_dir", "diff_cache_dir", "state_dir",
]


def repo_root() -> Path:
    env = os.environ.get("OSS_BUGFIXES_ROOT")
    if env:
        return Path(env).expanduser().resolve()
    return Path(__file__).resolve().parent.parent


def work_root() -> Path:
    env = os.environ.get("OSS_BUGFIXES_WORK")
    return (Path(env).expanduser().resolve() if env else repo_root() / "work")


def domains_root() -> Path:
    return repo_root() / "domains"


def domain_dir(domain: str) -> Path:
    return domains_root() / domain


def registry_path(domain: str) -> Path:
    """The registry file. `.yml` is canonical; `.json` is accepted so a domain
    can be generated by tooling that would rather not emit YAML."""
    d = domain_dir(domain)
    for name in ("repos.yml", "repos.yaml", "repos.json"):
        p = d / name
        if p.exists():
            return p
    return d / "repos.yml"


def domain_data_dir(domain: str) -> Path:
    return domain_dir(domain) / "data"


def domain_docs_dir(domain: str) -> Path:
    return domain_dir(domain) / "docs"


def work_dir(domain: str) -> Path:
    return work_root() / domain


def mirror_dir(domain: str) -> Path:
    return work_dir(domain) / "mirrors"


def commits_dir(domain: str) -> Path:
    return work_dir(domain) / "commits"


def candidates_dir(domain: str) -> Path:
    return work_dir(domain) / "candidates"


def diff_cache_dir(domain: str) -> Path:
    return work_dir(domain) / "diffs"


def state_dir(domain: str) -> Path:
    return work_dir(domain) / "state"


def list_domains() -> list[str]:
    root = domains_root()
    if not root.is_dir():
        return []
    return sorted(p.name for p in root.iterdir() if p.is_dir() and not p.name.startswith("."))
